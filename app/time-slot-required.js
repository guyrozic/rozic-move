/** הפורמט היחיד שהמערכת מכירה כחלון זמן: `HH:MM-HH:MM`. */
const SLOT_SHAPE = /^\d{1,2}:\d{2}-\d{1,2}:\d{2}$/;

/**
 * `null` כשיש חלון זמן תקין, או `{ title, body }`.
 *
 * ⚠️ **שלוש צורות של "אין שעה":** `''` (אתחול המצב), `null` (מה שנכתב
 * על ההזמנה) ו-`undefined` (שדה שלא נשמר בטיוטה). בדיקה על אחת מהן
 * בלבד עוברת על השתיים האחרות.
 */
export function checkTimeSlot(timeSlot) {
  const value = String(timeSlot ?? '').trim();
  if (!value || !SLOT_SHAPE.test(value)) {
    return {
      title: 'לא נבחר חלון זמן',
      body: 'כדי שהמוביל יוכל לתכנן את היום שלו צריך לבחור חלון זמן. חזור שלב אחורה ובחר אחד.',
    };
  }
  return null;
}
