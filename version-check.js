/**
 * "יש גרסה חדשה" — **בתוך חותמת הבנייה עצמה**, לא ברצועה נפרדת.
 *
 * ## למה זה קיים
 * ⚠️ **זו הפעם השנייה שהבעיה הזאת אוכלת סבבים שלמים.** ב-15.9 נוספה
 * חותמת הבנייה הגלויה בדיוק מהסיבה הזאת, וההערה שם אומרת "בזבזנו על
 * זה סבבים שלמים". ב-20.9 זה חזר: שלוש פריסות רצופות נבדקו מול משוב
 * שהתייחס לגרסה ישנה, כי הטאב היה פתוח ולא נטען מחדש.
 *
 * `Cache-Control: max-age=600` פג אחרי עשר דקות, אבל דף **שכבר טעון**
 * לא מושך את עצמו שוב לעולם. הוא יכול להישאר פתוח שעות ולהציג
 * בנאמנות גרסה שכבר לא קיימת.
 *
 * ## ⚠️ למה זה לא רצועה
 * הגרסה הראשונה הציגה רצועה ברוחב מלא. גיא (20.9): "תסיר את השורה
 * הזאת! אני רוצה רק את הריבוע הקטן שרשום בו עודכן תאריך ושעה - זה
 * לגמרי מספיק." והוא גם צדק טכנית: בדף הבית ה-`nav` הוא
 * `position: fixed`, והרצועה — שנכנסת לזרימה הרגילה — נדחפה מתחתיו
 * ורצה מעל קישורי הניווט.
 *
 * ההתראה עברה לתוך החותמת: אותו ריבוע, שמחליף טקסט וצבע והופך
 * ללחיץ. שום אלמנט חדש בדף, שום דבר שיכול להתנגש בפריסה.
 *
 * ## ⚠️ אפס `import`
 * כמו `offline-banner.js`: דף שנטען כשהרשת גרועה לא ימשוך את ה-SDK
 * של Firebase, וכל מודול שתלוי בו מת בשקט.
 *
 * ## ⚠️ לא מרענן לבד
 * הריענון הוא לחיצה, לעולם לא אוטומטי. רענון יזום באמצע מילוי טופס
 * מוחק ללקוח את מה שהקליד — "תיקון" שגורם בדיוק לנזק שהוא בא למנוע.
 *
 * ⚠️ נמחק יחד עם חותמת הבנייה לפני השקה לציבור — שניהם מוזרקים
 * מ-`stamp-assets.mjs` ומחפשים באותו `data-build-stamp`.
 */

(() => {
  const el = document.querySelector('[data-build-stamp]');
  if (!el) return;

  const mine = el.textContent.replace('עודכן', '').trim();
  if (!mine) return;

  let shown = false;

  async function check() {
    if (shown || document.hidden) return;
    try {
      // ⚠️ `no-store` מדלג על מטמון הדפדפן, והפרמטר מדלג על מטמון
      // ה-CDN (`max-age=600` חל גם על הקובץ הזה). בלי שניהם הבדיקה
      // עצמה יכולה להחזיר תשובה ישנה — כלומר לשקר בדיוק על מה
      // שהיא באה לבדוק.
      const res = await fetch(`/version.txt?t=${Date.now()}`, { cache: 'no-store' });
      if (!res.ok) return;
      const live = (await res.text()).trim();
      if (!live || live === mine) return;
      markStale(live);
    } catch {
      // אין רשת, או שהקובץ טרם נפרס. שקט מכוון: `offline-banner`
      // הוא זה שמדבר על ניתוקים, ושתי הודעות על אותו דבר הן רעש.
    }
  }

  function markStale(live) {
    if (shown) return;
    shown = true;

    el.classList.add('is-stale');
    el.textContent = '';

    /* ⚠️ החותמת היא `aria-hidden` — היא מטא-דאטה של בנייה ואין סיבה
       להקריא אותה. מרגע שהיא הופכת לפקד לחיץ זה כבר לא נכון: פקד
       שקורא מסך אינו רואה הוא פקד שלא קיים. ה-`aria-hidden` יורד
       וה-`role="status"` מכריז על השינוי כשהוא קורה. */
    el.removeAttribute('aria-hidden');
    el.setAttribute('role', 'status');

    const btn = document.createElement('button');
    btn.type = 'button';
    btn.className = 'build-stamp-btn';
    /* ⚠️ טקסט קצר בכוונה. הגרסה הראשונה כללה את חותמת הזמן בגוף
       הכפתור, הצ'יפ יצא רחב פי שניים מהחותמת הרגילה, וקצה הלוגו
       "ROZIC MOVE" נחתך מתחתיו — נתפס בצילום, לא במדידה (בדיקת
       `elementFromPoint` על מרכז הלוגו החזירה "לא מכוסה", כי רק
       ראשו נחתך). כל הפרטים נשארים ב-`title`. */
    btn.textContent = 'גרסה חדשה · רענן';
    btn.title = `נפרסה גרסה מ-${live}. מה שמוצג כאן הוא מ-${mine}.`;
    btn.addEventListener('click', () => location.reload());
    el.appendChild(btn);
  }

  // בטעינה, בכל חזרה לטאב, ואחת לחמש דקות. החזרה לטאב היא המקרה
  // שבו זה באמת קורה: משאירים דף פתוח, הולכים, וחוזרים.
  check();
  document.addEventListener('visibilitychange', () => { if (!document.hidden) check(); });
  setInterval(check, 5 * 60 * 1000);
})();
